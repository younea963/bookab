
import { createSlice, createAsyncThunk } from "@reduxjs/toolkit"; // createSlice: creates reducer + action creators
// createAsyncThunk: handles async logic (API calls, etc.)
import axios from "axios"; //  axios is to talk to  backend / API




// createAsyncThunk creates an async action
export const fetchData = createAsyncThunk(
  "featureName/fetchData", // "featureName/fetchData" is an INTERNAL Redux action type prefix (NOT a route)
  async () => {
    const response = await axios.get("/api/words"); // Call  backend API
    return response.data; // Anything returned becomes action.payload
  }
);

export const addWord = createAsyncThunk(
  "words/addWord",
  async (wordData) => {
    const response = await axios.post("/api/words", wordData, { withCredentials: true });
    return response.data; // Anything returned becomes action.payload
  }
);





// Define the shape of this slice of state
const initialState = {
  items: [],        // The actual data (array, object, etc.)
  status: "idle",   // Tracks async state: idle | loading | succeeded | failed
  error: null,      // Stores error message if request fails
};

//  SLICE DEFINITION

const featureSlice = createSlice({
  name: "featureName",  // Name of this slice (used in action types & Redux DevTools)
  initialState,   // Initial state for this slice


  reducers: {   // These run immediately and do NOT involve async logic (i.e. they're synchronous reducers)
    // Clears all stored data and resets status
    clearData(state) {
      state.items = [];
      state.status = "idle";
      state.error = null;
    },
   
    addItem(state, action) { // Adds a single item to the state
      state.items.push(action.payload);  // action.payload contains whatever was passed to dispatch(...)
    }
  },


  // ASYNC REDUCERS (THUNK LIFECYCLE)

  extraReducers: (builder) => {   // These respond to actions generated by createAsyncThunk

    // Runs automatically when fetchData() is dispatched
    // and the request has started
    builder.addCase(fetchData.pending, (state) => {
      state.status = "loading";
    });

    // Runs automatically when the request succeeds
    builder.addCase(fetchData.fulfilled, (state, action) => {
      state.status = "succeeded";

      // action.payload === data returned from the thunk
      state.items = action.payload;
    });

    // Runs automatically if the request fails
    builder.addCase(fetchData.rejected, (state, action) => {
      state.status = "failed";

      // Store the error message for UI display/debugging
      state.error = action.error.message;
    
    

    });
    builder.addCase(addWord.fulfilled, (state, action) => {
      state.items.unshift(action.payload.newWord);
    });
  },
});



// Export synchronous action creators
// These are used like: dispatch(clearData()) or dispatch(addItem(item))
export const { clearData, addItem } = featureSlice.actions;

// Export the reducer to be registered in the Redux store
export default featureSlice.reducer;
